#!/usr/bin/env python3
"""Generate the cross-platform parity map from co-located `@parity <slug>` tags.

The parity anchors are the single source of truth: every file that has a
counterpart in another platform carries a comment

    // @parity dsp/gated-fft        (Swift / TypeScript)
    # @parity dsp/gated-fft         (Python)

where the *slug* is a stable, area-namespaced join key. This tool scans all
three sibling repos, groups files by slug, and emits three artifacts (all
committed in the Swift repo so they live in one place on GitHub):

    parity-index.json   the database — one record per group
    PARITY-MAP.md       a single self-contained table (Ctrl-F any column)
    (parity_lookup.py)  a separate query utility that reads the JSON

Because paths are *discovered* by grouping (never restated in the tags), the
three copies of a mapping can never disagree, and a canonical-side rename can't
leave a stale path — the only failure mode is a slug that lands in exactly one
repo (a typo, or something that should be `@parity none`), which `--check`
reports.

Usage:
    python3 gen_parity_map.py            # regenerate PARITY-MAP.md + parity-index.json
    python3 gen_parity_map.py --check    # verify they're current + no orphan slugs (CI)

Repo roots are the script's own repo (Swift) and its siblings `guitar_tap`
(Python) and `GuitarTapWeb` (Web) under the same parent; override with the
env vars PARITY_SWIFT / PARITY_PYTHON / PARITY_WEB.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

# ── Configuration ────────────────────────────────────────────────────────────
SCRIPT = Path(__file__).resolve()
SELF_DIR = SCRIPT.parent                 # the parity tooling dir — never scan our own examples
SWIFT_ROOT = SCRIPT.parents[2]          # …/GuitarTap/Tooling/parity/ -> …/GuitarTap
SRC = SWIFT_ROOT.parent                 # …/src

REPOS: dict[str, Path] = {
    "swift": Path(os.environ.get("PARITY_SWIFT", SWIFT_ROOT)),
    "python": Path(os.environ.get("PARITY_PYTHON", SRC / "guitar_tap")),
    "web": Path(os.environ.get("PARITY_WEB", SRC / "GuitarTapWeb")),
}
PLATFORMS = ("swift", "python", "web")   # column order in the map / JSON

MAP_MD = SWIFT_ROOT / "PARITY-MAP.md"
INDEX_JSON = SWIFT_ROOT / "parity-index.json"

SRC_EXT = {".swift", ".py", ".ts", ".tsx", ".js", ".css"}
SKIP_DIRS = {
    ".git", "node_modules", "dist", "build", ".build", "DerivedData",
    "__pycache__", "Pods", ".venv", "venv", "coverage", ".vite", ".idea",
}

RESERVED_NONE = "none"
TAG_RE = re.compile(r"@parity\s+([A-Za-z0-9][\w./-]*)((?:[ \t]+[a-z]+=[\w./,-]+)*)")
SLUG_RE = re.compile(r"^[a-z0-9]+(?:[/-][a-z0-9]+)*$")   # area-namespaced kebab
ORACLE_WEB_RE = re.compile(r"(^|/)g\d")                  # web oracle test file (g1-…, g4c-…)

GEN_MARKER = "<!-- BEGIN GENERATED — regenerated by Tooling/parity/gen_parity_map.py; do not edit below -->"

DEFAULT_INTRO = f"""# Parity Map — GuitarTap (Swift) ↔ guitar_tap (Python) ↔ GuitarTapWeb

GuitarTapWeb is a long-term parallel port of **GuitarTap** (Swift, the **canonical
reference** for both algorithm and UX) and **guitar_tap** (Python, the mirror). The
three repos keep separate, idiomatic source trees. The binding parity contract is the
**oracle** (`parity-oracle.json` + `sync-oracle.sh --check`); this map is the source of
truth for **where the corresponding code lives**.

Each mirrored file carries a co-located `@parity <slug>` comment. This file is
generated from those tags — **do not hand-edit the tables below the marker**; edit the
tags and run `Tooling/parity/gen_parity_map.py`. To look up from any platform, Ctrl-F
the path you're holding (it appears only in its own column; the row gives the other
two), or use `Tooling/parity/parity_lookup.py <substring>` for sorted/filtered browsing.

{GEN_MARKER}
"""


# ── Scan ─────────────────────────────────────────────────────────────────────
class Tag:
    __slots__ = ("repo", "relpath", "slug", "lineno", "attrs")

    def __init__(self, repo: str, relpath: str, slug: str, lineno: int, attrs: dict):
        self.repo = repo
        self.relpath = relpath
        self.slug = slug
        self.lineno = lineno
        self.attrs = attrs


def parse_attrs(tail: str) -> dict:
    """Parse trailing `key=val` attributes on a tag (e.g. `tests=test/peaks,test/plate`)."""
    attrs: dict[str, list[str]] = {}
    for tok in tail.split():
        if "=" in tok:
            k, v = tok.split("=", 1)
            attrs[k] = [x for x in v.split(",") if x]
    return attrs


def scan_repo(repo: str, root: Path) -> list[Tag]:
    tags: list[Tag] = []
    if not root.exists():
        print(f"warning: repo root for '{repo}' not found: {root}", file=sys.stderr)
        return tags
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS and not d.startswith(".")]
        for name in filenames:
            if Path(name).suffix not in SRC_EXT:
                continue
            fpath = Path(dirpath) / name
            if SELF_DIR == fpath.parent or SELF_DIR in fpath.parents:
                continue  # skip the parity tooling itself (its docstrings show example tags)
            try:
                text = fpath.read_text(encoding="utf-8", errors="ignore")
            except OSError:
                continue
            if "@parity" not in text:
                continue
            rel = str(fpath.relative_to(root))
            for i, line in enumerate(text.splitlines(), 1):
                for m in TAG_RE.finditer(line):
                    tags.append(Tag(repo, rel, m.group(1), i, parse_attrs(m.group(2))))
    return tags


# ── Model ────────────────────────────────────────────────────────────────────
def build_index(all_tags: list[Tag]) -> tuple[list[dict], list[dict], list[dict]]:
    """Return (groups, platform_specific, problems).

    groups: [{slug, swift:[...], python:[...], web:[...]}] sorted by slug.
    platform_specific: [{repo, path}] for `@parity none`.
    problems: [{kind, ...}] — orphan slugs and malformed slugs.
    """
    groups: dict[str, dict[str, list[str]]] = {}
    group_tests: dict[str, set[str]] = {}   # slug -> linked test-group slugs (from tests=)
    platform_specific: list[dict] = []
    problems: list[dict] = []

    for t in all_tags:
        if t.slug == RESERVED_NONE:
            platform_specific.append({"repo": t.repo, "path": t.relpath})
            continue
        if not SLUG_RE.match(t.slug):
            problems.append({
                "kind": "malformed-slug", "slug": t.slug,
                "repo": t.repo, "path": t.relpath, "lineno": t.lineno,
            })
            # Still index it, so the map surfaces the group.
        g = groups.setdefault(t.slug, {p: [] for p in PLATFORMS})
        if t.relpath not in g[t.repo]:
            g[t.repo].append(t.relpath)
        group_tests.setdefault(t.slug, set()).update(t.attrs.get("tests", []))

    for repo_list in groups.values():
        for p in PLATFORMS:
            repo_list[p].sort()

    # Orphan: a real slug present in exactly one repo (typo, or should be `none`).
    for slug, g in groups.items():
        present = [p for p in PLATFORMS if g[p]]
        if len(present) == 1:
            problems.append({
                "kind": "orphan-slug", "slug": slug, "repo": present[0],
                "paths": g[present[0]],
            })

    group_list = [
        {"slug": slug, **{p: groups[slug][p] for p in PLATFORMS},
         "tests": sorted(group_tests.get(slug, set()))}
        for slug in sorted(groups)
    ]
    compute_equivalence(group_list, problems)
    platform_specific.sort(key=lambda e: (e["repo"], e["path"]))
    return group_list, platform_specific, problems


def compute_equivalence(group_list: list[dict], problems: list[dict]) -> None:
    """Derive each group's equivalence evidence from its linked `test/*` groups.

    A `test/*` group *is* the evidence. An impl group linked (via `tests=`) to a
    test group is oracle-backed if that test group has a `g#-…` web oracle test,
    and tests-backed if it has both Swift and Python members. Unlinked impl groups
    are "review only" — location asserted, equivalence not machine-checked. A
    `tests=` pointing at a missing / non-test group is a problem.
    """
    by_slug = {g["slug"]: g for g in group_list}
    for g in group_list:
        if g["slug"].startswith("test/"):
            g["equivalence"] = "test suite"
            continue
        oracle = paired = False
        for ts in g["tests"]:
            tg = by_slug.get(ts)
            if tg is None or not ts.startswith("test/"):
                problems.append({"kind": "bad-tests-ref", "slug": g["slug"], "ref": ts})
                continue
            if any(ORACLE_WEB_RE.search(p) for p in tg["web"]):
                oracle = True
            if tg["swift"] and tg["python"]:
                paired = True
        g["equivalence"] = (
            "oracle + tests" if oracle and paired else
            "oracle" if oracle else
            "tests" if paired or g["tests"] else
            "review only"
        )


# ── Render ───────────────────────────────────────────────────────────────────
def _cell(paths: list[str]) -> str:
    if not paths:
        return "—"
    return "<br>".join(f"`{p}`" for p in paths)


def render_markdown(groups: list[dict], platform_specific: list[dict]) -> str:
    intro = DEFAULT_INTRO
    if MAP_MD.exists():
        existing = MAP_MD.read_text(encoding="utf-8")
        if GEN_MARKER in existing:
            intro = existing.split(GEN_MARKER)[0] + GEN_MARKER + "\n"

    lines = [intro, "", "## Groups", "",
             "| slug | Swift | Python | Web | Equivalence |", "|---|---|---|---|---|"]
    for g in groups:
        lines.append(
            f"| `{g['slug']}` | {_cell(g['swift'])} | {_cell(g['python'])} | {_cell(g['web'])} "
            f"| {g.get('equivalence', '—')} |"
        )
    lines += [
        "",
        "**Equivalence** - where the contents are actually *verified* to match (this map only "
        "asserts co-location; behaviour is proven elsewhere). From each impl group's linked "
        "`test/*` group (tag attribute `tests=`): **oracle + tests** = numerically pinned by the "
        "oracle (a `g#` web test) AND covered by paired Swift/Python behavioural tests; **oracle** "
        "or **tests** = one of those; **test suite** = the row is itself a test; **review only** = "
        "no machine check (equivalence rests on change-all-three-together + code review).",
        "",
        "A `—` is a legitimate group with no member in that platform (e.g. a "
        "Swift↔Python-only test). Only a slug present in exactly one repo is an error.",
        "",
        "## Platform-specific (no parity) — `@parity none`",
        "",
        "| File | Repo |", "|---|---|",
    ]
    if platform_specific:
        for e in platform_specific:
            lines.append(f"| `{e['path']}` | {e['repo']} |")
    else:
        lines.append("| _(none tagged yet)_ | |")
    lines.append("")
    return "\n".join(lines)


def render_json(groups: list[dict], platform_specific: list[dict]) -> str:
    payload = {
        "groups": groups,
        "platformSpecific": platform_specific,
    }
    return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"


# ── Commands ─────────────────────────────────────────────────────────────────
def collect() -> tuple[list[dict], list[dict], list[dict]]:
    all_tags: list[Tag] = []
    for repo, root in REPOS.items():
        all_tags.extend(scan_repo(repo, root))
    return build_index(all_tags)


def print_problems(problems: list[dict]) -> None:
    for p in problems:
        if p["kind"] == "orphan-slug":
            print(f"  ORPHAN  `{p['slug']}` only in {p['repo']}: {', '.join(p['paths'])} "
                  f"(typo, or should it be `@parity none`?)", file=sys.stderr)
        elif p["kind"] == "malformed-slug":
            print(f"  MALFORMED  `{p['slug']}` at {p['repo']}:{p['path']}:{p['lineno']} "
                  f"(want area-namespaced kebab, e.g. dsp/gated-fft)", file=sys.stderr)
        elif p["kind"] == "bad-tests-ref":
            print(f"  BAD tests=  `{p['slug']}` links to `{p['ref']}`, which is not an "
                  f"existing test/* group", file=sys.stderr)


def cmd_generate() -> int:
    groups, platform_specific, problems = collect()
    MAP_MD.write_text(render_markdown(groups, platform_specific), encoding="utf-8")
    INDEX_JSON.write_text(render_json(groups, platform_specific), encoding="utf-8")
    print(f"wrote {MAP_MD.relative_to(SWIFT_ROOT)} and {INDEX_JSON.relative_to(SWIFT_ROOT)}: "
          f"{len(groups)} groups, {len(platform_specific)} platform-specific.")
    if problems:
        print(f"{len(problems)} problem(s):", file=sys.stderr)
        print_problems(problems)
    return 0


def cmd_check() -> int:
    groups, platform_specific, problems = collect()
    want_md = render_markdown(groups, platform_specific)
    want_json = render_json(groups, platform_specific)
    stale = []
    if not MAP_MD.exists() or MAP_MD.read_text(encoding="utf-8") != want_md:
        stale.append(str(MAP_MD.relative_to(SWIFT_ROOT)))
    if not INDEX_JSON.exists() or INDEX_JSON.read_text(encoding="utf-8") != want_json:
        stale.append(str(INDEX_JSON.relative_to(SWIFT_ROOT)))

    ok = True
    if stale:
        ok = False
        print(f"parity map out of date: {', '.join(stale)} — run "
              f"Tooling/parity/gen_parity_map.py", file=sys.stderr)
    if problems:
        ok = False
        counts: dict[str, int] = {}
        for p in problems:
            counts[p["kind"]] = counts.get(p["kind"], 0) + 1
        print("problems: " + ", ".join(f"{n} {k}" for k, n in sorted(counts.items())),
              file=sys.stderr)
        print_problems(problems)
    if ok:
        print(f"parity map current: {len(groups)} groups, {len(platform_specific)} "
              f"platform-specific, no problems.")
        return 0
    return 1


def main() -> int:
    ap = argparse.ArgumentParser(description="Generate/verify the cross-platform parity map.")
    ap.add_argument("--check", action="store_true",
                    help="verify PARITY-MAP.md + parity-index.json are current and "
                         "there are no orphan/malformed slugs (exit 1 on failure)")
    args = ap.parse_args()
    return cmd_check() if args.check else cmd_generate()


if __name__ == "__main__":
    raise SystemExit(main())